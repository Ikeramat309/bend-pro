function frac(s) {
  // "4-3/16" | "5-1/8" | "7-1/2" | "13 1/2" | "3.69" | "21 1/2"
  if (typeof s === 'number') return s;
  const t = String(s).trim().replace(/"/g, '').replace(/″/g, '');
  if (/^\d+(\.\d+)?$/.test(t)) return Number(t);
  const m1 = t.match(/^(\d+)-(\d+)\/(\d+)$/);
  if (m1) return Number(m1[1]) + Number(m1[2]) / Number(m1[3]);
  const m2 = t.match(/^(\d+)\s+(\d+)\/(\d+)$/);
  if (m2) return Number(m2[1]) + Number(m2[2]) / Number(m2[3]);
  const m3 = t.match(/^(\d+)\/(\d+)$/);
  if (m3) return Number(m3[1]) / Number(m3[2]);
  throw new Error(`Cannot parse fraction: ${s}`);
}

