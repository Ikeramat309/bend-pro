function addFact(f) {
  const normalized =
    f.normalizedValueInches === undefined
      ? f.originalValue === null || f.originalUnit === 'none' || f.originalUnit === 'degree'
        ? null
        : typeof f.originalValue === 'number'
          ? f.originalValue
          : frac(f.originalValue)
      : f.normalizedValueInches;
  measurements.push({
    accessoryOrShoeId: null,
    operation: null,
    page: null,
    section: null,
    table: null,
    excerpt: null,
    conflictGroupId: null,
    notes: '',
    productionScope: 'emt_in_scope',
    ...f,
    normalizedValueInches: normalized,
  });
}

