#!/usr/bin/env node
/**
 * Rebuilds icon-family-preview.svg by embedding standalone icon SVGs.
 * Prevents preview drift from icons/*.svg.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ICONS = path.join(ROOT, 'assets', 'icons');
const OUT = path.join(ROOT, 'assets', 'previews', 'icon-family-preview.svg');

const ICON_IDS = [
  'icon-hand-aluminum',
  'icon-hand-iron',
  'icon-hand-dual-head',
  'icon-hand-angle-setter',
  'icon-mechanical-ratchet',
  'icon-electric',
  'icon-hydraulic',
  'icon-bender-shoe',
  'icon-shoe-set',
  'icon-custom-measured',
  'icon-generic-field-reference',
  'icon-status-verified',
  'icon-status-reference-only',
  'icon-status-conflict',
];

function extractInner(svgText) {
  // Strip outer svg wrapper; keep children
  return svgText
    .replace(/<\?xml[^>]*>/g, '')
    .replace(/<svg[^>]*>/i, '')
    .replace(/<\/svg>\s*$/i, '')
    .trim();
}

const symbols = ICON_IDS.map((id) => {
  const raw = fs.readFileSync(path.join(ICONS, `${id}.svg`), 'utf8');
  const inner = extractInner(raw);
  return `  <symbol id="${id}" viewBox="0 0 24 24">\n${inner
    .split('\n')
    .map((l) => `    ${l}`)
    .join('\n')}\n  </symbol>`;
}).join('\n');

// Two theme panels: 24px review strip + size ladder
function buildPanelContent(y0, bg, ink, muted, title) {
  let b = '';
  b += `  <rect x="16" y="${y0}" width="948" height="780" rx="12" fill="${bg}" stroke="${muted}" stroke-opacity="0.35"/>\n`;
  b += `  <text x="40" y="${y0 + 32}" fill="${ink}" font-family="system-ui,Segoe UI,sans-serif" font-size="18" font-weight="600">${title}</text>\n`;
  b += `  <text x="40" y="${y0 + 52}" fill="${muted}" font-family="system-ui,Segoe UI,sans-serif" font-size="12">Device-scale 24px review (phone list density) · then 32 / 48 / 96</text>\n`;

  // 24px strip — all 14
  b += `  <text x="40" y="${y0 + 78}" fill="${muted}" font-family="system-ui,Segoe UI,sans-serif" font-size="11">24px</text>\n`;
  ICON_IDS.forEach((id, i) => {
    const x = 40 + (i % 14) * 64;
    const y = y0 + 90 + Math.floor(i / 14) * 40;
    b += `  <g color="${ink}"><use href="#${id}" x="${x}" y="${y}" width="24" height="24"/></g>\n`;
  });

  let y = y0 + 140;
  for (const size of [32, 48, 96]) {
    b += `  <text x="40" y="${y}" fill="${muted}" font-family="system-ui,Segoe UI,sans-serif" font-size="11">${size}px</text>\n`;
    ICON_IDS.forEach((id, i) => {
      const col = i % 7;
      const row = Math.floor(i / 7);
      const x = 40 + col * 130;
      const yy = y + 10 + row * (size + 28);
      b += `  <g color="${ink}"><use href="#${id}" x="${x}" y="${yy}" width="${size}" height="${size}"/></g>\n`;
    });
    y += 10 + 2 * (size + 28) + 16;
  }
  return b;
}

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 980 1680" fill="none">
  <title>Bend Pro bender icon family preview</title>
  <desc>Light and dark panels. Symbols are generated from assets/icons/*.svg to prevent drift. 14 standalone icons; this preview is not an icon.</desc>
  <rect width="980" height="1680" fill="#E8EAED"/>
  <text x="40" y="36" fill="#0E1116" font-family="system-ui,Segoe UI,sans-serif" font-size="20" font-weight="600">Bend Pro — Bender icon family preview</text>
  <text x="40" y="58" fill="#566070" font-family="system-ui,Segoe UI,sans-serif" font-size="12">Generated by scripts/build-icon-preview.mjs from standalone SVGs · original silhouettes · no manufacturer logos</text>
  <defs>
${symbols}
  </defs>
${buildPanelContent(80, '#FFFFFF', '#0E1116', '#566070', 'Light theme panel')}
${buildPanelContent(880, '#0E121A', '#F4F6F9', '#8A94A3', 'Dark theme panel')}
</svg>
`;

fs.writeFileSync(OUT, svg);
console.log('Wrote', OUT, 'with', ICON_IDS.length, 'embedded symbols');
